/**
 * Backfill operators + operator_identities from faa_operators.
 *
 * Phase 1 commit 6: FAA is the spine. For every faa_operators row with
 * a real-looking certificate number, we create one canonical operators
 * row + one operator_identities(source='faa') row.
 *
 * UPSTREAM DATA QUALITY NOTE:
 *   faa_operators contains 3,898 rows but only ~50 are real Part 135
 *   operators. The other ~3,846 are certificate_holder values from
 *   faa_aircraft — LLCs, trusts, and individual owners that got pulled
 *   into the operator table during faa-operators-full.ts ingestion
 *   without a proper operator filter. This backfill filters down to
 *   the ~50 rows with a cert-like certificate_number pattern; the rest
 *   are aircraft owners and belong in the Phase 3 aircraft canonical
 *   layer, not operators. Full details + follow-up plan:
 *   docs/phase1-followups.md.
 *
 * FILTER (two regex patterns that match real cert IDs):
 *   - ^[A-Z]{4}[0-9]{3}$          synthetic codes (NETJ001, FLEX001, ...)
 *                                 generated by faa-operators-full.ts
 *                                 from the ICAO_OPERATOR_MAP
 *   - ^[0-9][A-Z]{3}[0-9]{3}[A-Z]$  actual FAA Part 135 cert format
 *                                   (e.g. 1OCA082A Priester Aviation)
 *   Combined with: certificate_number != name (filters out rows where
 *   cert was populated with the legal entity name).
 *
 * Note: the synthetic codes are stable internal IDs, not real FAA
 * certificates. operator_identities.source_id stores whatever the row
 * carries; commit 7's safety_ratings matcher uses name-fuzzy matching,
 * not cert_number join, so this is fine. The original 1-of-313 match
 * problem was assuming cross-source cert alignment; name-based MDM
 * is the fix.
 *
 * Defaults to dry-run (prints counts + sample, writes nothing).
 * Pass --commit to actually write.
 *
 * Idempotent: re-running only bumps last_verified_at on already-existing
 * (source='faa', source_id=cert) identities. No duplicate operators.
 *
 * Deferred:
 *   - type_tags: left as empty '{}'. The current faa_operators schema has
 *     no category / part-135 flag column (see docs/schema.md). Enrichment
 *     via fleet analysis lands in a later phase.
 *   - headquarters_icao: NULL. Fabricating ICAO from city/state is worse
 *     than null. Derivation from ADS-B most-frequent-origin comes later.
 *   - operator_aliases: deferred; user scope for this commit is
 *     operators + operator_identities only.
 *
 * Usage:
 *   DATABASE_TYPE=postgres npm run operators:backfill-faa            # dry run
 *   DATABASE_TYPE=postgres npm run operators:backfill-faa -- --commit
 */

import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import pg from "pg";
import { getPool, closePg } from "../src/memory/pg-database.js";
import { initSentry, flushSentry, installProcessHandlers } from "../src/utils/sentry.js";
import { childLogger } from "../src/utils/logger.js";

const log = childLogger("faa-backfill");

const BATCH_SIZE = 500;

/**
 * Two regex patterns that match real operator cert IDs. Keep SQL and JS
 * in sync — the SQL runs the server-side WHERE; the JS regex is exposed
 * for isRealOperatorCert() and tests.
 */
export const CERT_REGEX_SYNTHETIC = /^[A-Z]{4}[0-9]{3}$/;
export const CERT_REGEX_FAA_PART135 = /^[0-9][A-Z]{3}[0-9]{3}[A-Z]$/;

export function isRealOperatorCert(cert: string, name: string): boolean {
  if (cert === name) return false;
  return CERT_REGEX_SYNTHETIC.test(cert) || CERT_REGEX_FAA_PART135.test(cert);
}

// ── Types ────────────────────────────────────────────────────────────────

export interface FaaOperatorRow {
  certificate_number: string;
  name: string;
  dba_name: string | null;
  city: string | null;
  state: string | null;
  created_at: string | Date | null;
}

export interface CanonicalPayload {
  certificateNumber: string;
  canonicalName: string;
  typeTags: string[];
  firstSeenAt: Date;
}

// ── Pure helpers (testable) ──────────────────────────────────────────────

export function parseArgs(argv: string[]): { commit: boolean } {
  return { commit: argv.includes("--commit") };
}

/**
 * Derive the canonical-write payload from a faa_operators row.
 * type_tags stays empty in Phase 1 (no reliable source column); see header.
 */
export function classifyFaaOperator(row: FaaOperatorRow): CanonicalPayload {
  const firstSeenAt =
    row.created_at instanceof Date
      ? row.created_at
      : row.created_at
        ? new Date(row.created_at)
        : new Date();
  return {
    certificateNumber: row.certificate_number,
    canonicalName: (row.name ?? "").trim(),
    typeTags: [],
    firstSeenAt,
  };
}

export function splitNewVsExisting(
  rows: FaaOperatorRow[],
  existingCerts: ReadonlySet<string>,
): { newRows: FaaOperatorRow[]; updateCerts: string[] } {
  const newRows: FaaOperatorRow[] = [];
  const updateCerts: string[] = [];
  for (const r of rows) {
    if (existingCerts.has(r.certificate_number)) {
      updateCerts.push(r.certificate_number);
    } else {
      newRows.push(r);
    }
  }
  return { newRows, updateCerts };
}

// ── DB I/O ───────────────────────────────────────────────────────────────

async function loadFaaOperators(
  client: pg.PoolClient,
): Promise<{ total: number; real: FaaOperatorRow[] }> {
  const total = await client.query<{ cnt: string }>(
    `SELECT COUNT(*)::TEXT AS cnt FROM faa_operators`,
  );
  // See the CERT_REGEX_* constants above — two patterns that match real
  // operator IDs (synthetic + actual FAA Part 135 cert format). Everything
  // else in faa_operators is an aircraft owner that belongs in a different
  // canonical layer (tracked in docs/phase1-followups.md).
  const res = await client.query<FaaOperatorRow>(
    `SELECT certificate_number, name, dba_name, city, state, created_at
     FROM faa_operators
     WHERE certificate_number IS NOT NULL
       AND name IS NOT NULL
       AND TRIM(name) <> ''
       AND certificate_number != name
       AND (certificate_number ~ '^[A-Z]{4}[0-9]{3}$'
            OR certificate_number ~ '^[0-9][A-Z]{3}[0-9]{3}[A-Z]$')
     ORDER BY certificate_number`,
  );
  return { total: Number(total.rows[0]?.cnt ?? 0), real: res.rows };
}

async function loadExistingFaaCerts(client: pg.PoolClient): Promise<Set<string>> {
  const res = await client.query<{ source_id: string }>(
    `SELECT source_id FROM operator_identities WHERE source = 'faa'`,
  );
  return new Set(res.rows.map((r) => r.source_id));
}

async function bulkInsertBatch(
  client: pg.PoolClient,
  newRows: FaaOperatorRow[],
): Promise<{ operators: number; identities: number }> {
  if (newRows.length === 0) return { operators: 0, identities: 0 };

  // Bulk INSERT operators, preserving input order so we can align RETURNING ids.
  const opsValues: string[] = [];
  const opsParams: unknown[] = [];
  newRows.forEach((r, i) => {
    const p = classifyFaaOperator(r);
    const base = i * 3;
    opsValues.push(`($${base + 1}, $${base + 2}::TEXT[], $${base + 3})`);
    opsParams.push(p.canonicalName, p.typeTags, p.firstSeenAt);
  });
  const opsRes = await client.query<{ id: string }>(
    `INSERT INTO operators (canonical_name, type_tags, first_seen_at)
     VALUES ${opsValues.join(", ")}
     RETURNING id`,
    opsParams,
  );
  const newIds = opsRes.rows.map((r) => r.id);
  if (newIds.length !== newRows.length) {
    throw new Error(
      `operators INSERT returned ${newIds.length} rows, expected ${newRows.length}`,
    );
  }

  // Bulk INSERT operator_identities (one per new operator).
  const idValues: string[] = [];
  const idParams: unknown[] = [];
  newRows.forEach((r, i) => {
    const base = i * 4;
    idValues.push(
      `($${base + 1}, 'faa', $${base + 2}, $${base + 3}, 'exact', 'faa_cert_direct', $${base + 4}::jsonb)`,
    );
    const evidence = { method: "faa_registry_direct", cert_number: r.certificate_number };
    idParams.push(newIds[i], r.certificate_number, r.name, JSON.stringify(evidence));
  });
  const idRes = await client.query(
    `INSERT INTO operator_identities
       (operator_id, source, source_id, name_as_provided,
        match_confidence, match_method, match_evidence)
     VALUES ${idValues.join(", ")}`,
    idParams,
  );

  return { operators: opsRes.rowCount ?? 0, identities: idRes.rowCount ?? 0 };
}

async function bumpLastVerified(
  client: pg.PoolClient,
  certs: string[],
): Promise<number> {
  if (certs.length === 0) return 0;
  const res = await client.query(
    `UPDATE operator_identities
       SET last_verified_at = NOW()
     WHERE source = 'faa' AND source_id = ANY($1::TEXT[])`,
    [certs],
  );
  return res.rowCount ?? 0;
}

// ── Env load (same pattern as migrate-pg.ts) ────────────────────────────

function loadEnv(): void {
  try {
    const envContent = readFileSync(resolve(process.cwd(), ".env"), "utf-8");
    for (const line of envContent.split("\n")) {
      const t = line.trim();
      if (!t || t.startsWith("#")) continue;
      const eq = t.indexOf("=");
      if (eq < 0) continue;
      const key = t.slice(0, eq).trim();
      const val = t.slice(eq + 1).trim();
      if (!process.env[key]) process.env[key] = val;
    }
  } catch {
    // .env not found — fine, env vars may be set directly
  }
}

// ── Main ────────────────────────────────────────────────────────────────

async function main(): Promise<void> {
  loadEnv();
  if (process.env["DATABASE_TYPE"] !== "postgres") {
    throw new Error("operators:backfill-faa requires DATABASE_TYPE=postgres");
  }

  initSentry();
  installProcessHandlers("faa-backfill");

  const { commit } = parseArgs(process.argv.slice(2));
  const t0 = Date.now();

  const pool = getPool();
  const client = await pool.connect();
  try {
    console.log("[faa-backfill] Reading faa_operators...");
    const { total, real: faa } = await loadFaaOperators(client);
    const excluded = total - faa.length;
    console.log(`[faa-backfill] Found ${total} rows`);
    console.log(
      `[faa-backfill] Filtered to ${faa.length} real operators (excluded ${excluded} aircraft owners — see docs/phase1-followups.md)`,
    );

    const existing = await loadExistingFaaCerts(client);
    const { newRows, updateCerts } = splitNewVsExisting(faa, existing);
    console.log(
      `[faa-backfill] Proposed: ${newRows.length} new operators + ${newRows.length} identities; ${updateCerts.length} existing (last_verified_at bump)`,
    );

    const sample = newRows.slice(0, 10).map(classifyFaaOperator);
    if (sample.length > 0) {
      console.log(`[faa-backfill] Sample canonical rows:`);
      sample.forEach((s, i) => {
        console.log(`  ${i + 1}. '${s.canonicalName}' (cert=${s.certificateNumber})`);
      });
    }

    if (!commit) {
      console.log(`[faa-backfill] Dry run complete. Use --commit to write.`);
      await closePg();
      await flushSentry();
      return;
    }

    console.log(`[faa-backfill] Writing with transaction batches of ${BATCH_SIZE}...`);
    let insertedOps = 0;
    let insertedIds = 0;
    await client.query("BEGIN");
    try {
      for (let i = 0; i < newRows.length; i += BATCH_SIZE) {
        const batch = newRows.slice(i, i + BATCH_SIZE);
        const batchNum = Math.floor(i / BATCH_SIZE) + 1;
        const batchCount = Math.ceil(newRows.length / BATCH_SIZE);
        console.log(`[faa-backfill] Writing batch ${batchNum}/${batchCount} (${batch.length} rows)...`);
        const r = await bulkInsertBatch(client, batch);
        insertedOps += r.operators;
        insertedIds += r.identities;
      }
      const bumped = await bumpLastVerified(client, updateCerts);
      await client.query("COMMIT");
      console.log(`[faa-backfill] Inserted ${insertedOps} operators + ${insertedIds} identities; bumped ${bumped} existing`);
    } catch (err) {
      await client.query("ROLLBACK").catch(() => undefined);
      throw err;
    }

    // Verify
    const opsCount = await client.query<{ cnt: string }>(`SELECT COUNT(*)::TEXT AS cnt FROM operators`);
    const idsCount = await client.query<{ cnt: string }>(
      `SELECT COUNT(*)::TEXT AS cnt FROM operator_identities WHERE source = 'faa'`,
    );
    const dtSec = ((Date.now() - t0) / 1000).toFixed(1);
    console.log(
      `[faa-backfill] Verification: ${opsCount.rows[0]?.cnt} operators, ${idsCount.rows[0]?.cnt} FAA identities`,
    );
    console.log(`[faa-backfill] Done. ${dtSec}s`);
  } finally {
    client.release();
    await closePg();
    await flushSentry();
  }
}

const isMain = import.meta.url === pathToFileURL(process.argv[1] ?? "").href;
if (isMain) {
  main().catch((err) => {
    log.fatal({ err }, "faa-backfill fatal error");
    process.exit(1);
  });
}
